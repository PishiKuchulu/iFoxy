//! Regression tests for the third external-review wave (2026-10-31,
//! tree v1.0.21).
//!
//! Each test pins one fix so a later refactor cannot silently re-open
//! the hole the reviewer found. Findings covered here: C-1 (recovery
//! journal kept on incomplete recovery), C-2 (resolv.conf backup
//! validation before the elevated write), M-1 (APP_VERSION drift),
//! H-7 (DNS cache honours the response TTL).

use ifoxy_windows::vpn::netstack::dns_response_min_ttl;
use ifoxy_windows::vpn::network_backend::{MockNetworkBackend, NetworkBackend};
use ifoxy_windows::vpn::recovery_journal::{
    validate_resolv_conf_backup, JournalError, RecoveryJournal,
};
use ifoxy_windows::vpn::routing::{RouteDefinition, RouteError};
use ifoxy_windows::vpn::system_proxy::ProxySettingsBackup;
use std::net::Ipv4Addr;
use std::path::PathBuf;
use std::sync::Arc;

fn temp_journal(tag: &str) -> (PathBuf, PathBuf) {
    let dir = std::env::temp_dir().join(format!(
        "ifoxy_review3_{}_{}",
        tag,
        rand::random::<u64>()
    ));
    let _ = std::fs::create_dir_all(&dir);
    let path = dir.join("recovery_journal.json");
    (dir, path)
}

#[cfg(target_os = "linux")]
fn sample_backup() -> ProxySettingsBackup {
    ProxySettingsBackup {
        entries: vec![(
            "org.gnome.system.proxy".to_string(),
            "mode".to_string(),
            "'none'".to_string(),
        )],
    }
}

#[cfg(windows)]
fn sample_backup() -> ProxySettingsBackup {
    ProxySettingsBackup {
        proxy_enable: Some(0),
        proxy_server: None,
        proxy_override: None,
    }
}

/// M-1: the library's APP_VERSION used to be a hand-maintained literal
/// that drifted from Cargo.toml (0.2.1 vs 0.2.2). It is now derived
/// from the package version; pin the two together.
#[test]
fn test_app_version_matches_cargo_version() {
    assert_eq!(ifoxy_windows::APP_VERSION, env!("CARGO_PKG_VERSION"));
}

/// C-2: a realistic resolv.conf backup passes validation.
#[test]
fn test_resolv_conf_backup_validation_accepts_realistic_content() {
    let content = "\
# Generated by NetworkManager
nameserver 1.1.1.1
nameserver 2606:4700:4700::1111
search lan example.com
domain example.org
options ndots:2 timeout:1 attempts:3
sortlist 130.155.160.0/255.255.240.0
; a semicolon comment
";
    assert!(
        validate_resolv_conf_backup(content).is_ok(),
        "realistic resolv.conf must validate: {:?}",
        validate_resolv_conf_backup(content)
    );
}

/// C-2: hostile or malformed content is rejected before any write.
#[test]
fn test_resolv_conf_backup_validation_rejects_hostile_content() {
    let cases: &[&str] = &[
        // nameserver must be an IP literal, not a hostname or junk.
        "nameserver example.com\n",
        "nameserver 999.1.1.1\n",
        "nameserver\n",
        // Nothing may trail a nameserver directive.
        "nameserver 1.1.1.1 extra\n",
        "nameserver 1.1.1.1; rm -rf /\n",
        // Unknown directives are not resolv.conf shapes we restore.
        "bogusdirective foo\n",
        "updateresolvconf /tmp/evil\n",
        // Domain/option tokens may not smuggle flags or shell syntax.
        "search -evil.com\n",
        "search ok.com --bad\n",
        "options ndots:2|evil\n",
        "options $(reboot)\n",
        // sortlist entries must be IPs with an optional IP mask.
        "sortlist not-an-ip\n",
        "sortlist 10.0.0.0/33\n",
    ];
    for content in cases {
        assert!(
            validate_resolv_conf_backup(content).is_err(),
            "must reject: {content:?}"
        );
    }
    // The 64 KiB cap rejects padded payloads.
    let oversized = format!("nameserver 1.1.1.1\n#{}", "x".repeat(70 * 1024));
    assert!(validate_resolv_conf_backup(&oversized).is_err());
}

/// A backend whose proxy restore always fails, to exercise the C-1
/// hard-failure path in recovery.
struct ProxyFailBackend;

impl NetworkBackend for ProxyFailBackend {
    fn detect_default_gateway(&self) -> Result<Ipv4Addr, RouteError> {
        Ok(Ipv4Addr::new(192, 168, 1, 1))
    }
    fn add_route(&self, _route: &RouteDefinition, _if_index: u32) -> Result<(), RouteError> {
        Ok(())
    }
    fn delete_route(&self, _route: &RouteDefinition, _if_index: u32) -> Result<(), RouteError> {
        Ok(())
    }
    fn set_system_proxy(&self, _port: u16) -> Result<(), String> {
        Ok(())
    }
    fn restore_system_proxy(
        &self,
        _backup: Option<&ProxySettingsBackup>,
    ) -> Result<(), String> {
        Err("simulated proxy restore failure".to_string())
    }
}

/// C-1: when a recorded restore fails, recovery reports
/// RecoveryIncomplete and KEEPS the journal file so the next start
/// retries — the pre-fix code deleted the journal unconditionally and
/// the leftover state (proxy pointing at a dead listener) became
/// permanent and invisible.
#[test]
fn test_recovery_with_failing_proxy_restore_keeps_journal_and_errors() {
    let (dir, journal_path) = temp_journal("proxy_fail");
    let mut journal = RecoveryJournal::new(journal_path.clone());
    journal.record_proxy_backup(sample_backup());
    journal.flush_to_disk().unwrap();
    assert!(journal_path.exists());

    let backend = ProxyFailBackend;
    let result = RecoveryJournal::recover_if_dirty(&journal_path, &backend);
    match result {
        Err(JournalError::RecoveryIncomplete(msg)) => {
            assert!(
                msg.contains("proxy"),
                "error should name the failed restore, got: {msg}"
            );
        }
        other => panic!("expected RecoveryIncomplete error, got {other:?}"),
    }
    assert!(
        journal_path.exists(),
        "journal must be KEPT when recovery is incomplete"
    );

    let _ = std::fs::remove_dir_all(&dir);
}

/// C-1 (success side): when every restore succeeds, recovery returns
/// Ok(true) and removes the journal.
#[test]
fn test_recovery_success_removes_journal() {
    let (dir, journal_path) = temp_journal("success");
    let mock = Arc::new(MockNetworkBackend::new(Ipv4Addr::new(192, 168, 1, 1)));
    let mut journal = RecoveryJournal::new(journal_path.clone());
    journal.record_route(
        RouteDefinition {
            destination: Ipv4Addr::new(10, 0, 0, 0),
            prefix_len: 8,
            gateway: Ipv4Addr::new(192, 168, 1, 1),
            metric: 1,
        },
        3,
    );
    journal.record_proxy_backup(sample_backup());
    journal.flush_to_disk().unwrap();

    let recovered = RecoveryJournal::recover_if_dirty(&journal_path, mock.as_ref())
        .expect("recovery with a healthy backend must succeed");
    assert!(recovered, "dirty journal should report recovery ran");
    assert!(
        !journal_path.exists(),
        "journal must be removed after a fully successful recovery"
    );
    assert_eq!(mock.deleted_count(), 1, "recorded route must be replayed");

    let _ = std::fs::remove_dir_all(&dir);
}

/// C-1 + C-2: a journal whose resolv.conf backup fails validation is a
/// hard failure — error, journal kept, and the system resolv.conf is
/// byte-identical afterwards (nothing was written).
#[test]
fn test_recovery_with_invalid_resolv_backup_errors_and_writes_nothing() {
    let (dir, journal_path) = temp_journal("bad_resolv");
    let before = std::fs::read("/etc/resolv.conf").ok();

    let mut journal = RecoveryJournal::new(journal_path.clone());
    journal.record_resolv_conf_backup("nameserver not-an-ip\n".to_string());
    journal.flush_to_disk().unwrap();

    let mock = Arc::new(MockNetworkBackend::new(Ipv4Addr::new(192, 168, 1, 1)));
    let result = RecoveryJournal::recover_if_dirty(&journal_path, mock.as_ref());
    assert!(
        matches!(result, Err(JournalError::RecoveryIncomplete(_))),
        "invalid resolv.conf backup must fail recovery, got {result:?}"
    );
    assert!(journal_path.exists(), "journal must be kept for retry");

    let after = std::fs::read("/etc/resolv.conf").ok();
    assert_eq!(
        before, after,
        "/etc/resolv.conf must not be touched when validation rejects the backup"
    );

    let _ = std::fs::remove_dir_all(&dir);
}

/// H-7: the DNS cache used to ignore upstream TTLs entirely (fixed
/// 60 s). The TTL parser takes the minimum across answer records.
#[test]
fn test_dns_response_min_ttl_parsing() {
    // Header: id, flags, qd=1, an=2, ns=0, ar=0.
    let mut msg: Vec<u8> = vec![
        0x12, 0x34, 0x81, 0x80, 0x00, 0x01, 0x00, 0x02, 0x00, 0x00, 0x00, 0x00,
    ];
    // Question: example.com, type A, class IN.
    msg.extend_from_slice(b"\x07example\x03com\x00");
    msg.extend_from_slice(&[0x00, 0x01, 0x00, 0x01]);
    // Answer 1: pointer to the question name, A/IN, TTL 300, 1.2.3.4.
    msg.extend_from_slice(&[0xC0, 0x0C, 0x00, 0x01, 0x00, 0x01]);
    msg.extend_from_slice(&300u32.to_be_bytes());
    msg.extend_from_slice(&[0x00, 0x04, 1, 2, 3, 4]);
    // Answer 2: same name, A/IN, TTL 45, 5.6.7.8.
    msg.extend_from_slice(&[0xC0, 0x0C, 0x00, 0x01, 0x00, 0x01]);
    msg.extend_from_slice(&45u32.to_be_bytes());
    msg.extend_from_slice(&[0x00, 0x04, 5, 6, 7, 8]);

    assert_eq!(dns_response_min_ttl(&msg), Some(45));

    // No answers -> None (the caller falls back to the default TTL).
    let mut no_answers = msg.clone();
    no_answers[6] = 0;
    no_answers[7] = 0;
    assert_eq!(dns_response_min_ttl(&no_answers), None);

    // Truncated garbage -> None, never a panic.
    assert_eq!(dns_response_min_ttl(&msg[..10]), None);
    assert_eq!(dns_response_min_ttl(&msg[..20]), None);
    assert_eq!(dns_response_min_ttl(&[]), None);
}
